import { DataTypes } from "sequelize";
import { sequelizeInstance } from "./conn";

export const User = sequelizeInstance.define("user", {
  name: {
    type: DataTypes.STRING,
    allowNull: false,
  },
  email: {
    type: DataTypes.STRING,
    allowNull: false,
    unique: true,
  },
  password: {
    type: DataTypes.STRING,
    allowNull: false,
  },
});
